def image(path):
    """A reproducible synthetic RGB sensor field, sized to exercise chunking."""
    def chunk(kind, raw):
        return struct.pack('!I', len(raw)) + kind + raw + struct.pack('!I', zlib.crc32(kind + raw))
    state = 123456789
    data = bytearray()
    for row in range(720):
        data.append(0)
        for col in range(720 * 3):
            state ^= (state << 13) & 0xffffffff
            state ^= state >> 17
            state ^= (state << 5) & 0xffffffff
            data.append(state & 255)
    header = struct.pack('!IIBBBBB', 720, 720, 8, 2, 0, 0, 0)
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', header) + chunk(b'IDAT', zlib.compress(data)) + chunk(b'IEND', b''))


def run(output, texlive_root):
    output = no_links(Path(output))
    output.mkdir(parents=True, exist_ok=False)
    project = output / 'project'; paper = project / 'PaperWriting'
    paper.mkdir(parents=True)
    for name in ['templates', 'references', 'materials', 'reviews']:(paper / name).mkdir()
    (project / 'results').mkdir()
    initialize(project_root=project, paper_root=paper, project_id='bilingual-synthetic',
        project_name='Synthetic bilingual section workflow', target_venue='Generic example')
    image(paper / 'materials' / 'synthetic-field.png')
    (paper / 'references' / 'demo.bib').write_text('@misc{SyntheticFixture2026,title={Synthetic workflow fixture; no research claim},author={Example Author},year={2026}}\n')
    template = (r'\documentclass[UTF8,fontset=fandol]{ctexart}' '\n'
        r'\usepackage{graphicx}' '\n' r'\begin{document}' '\n'
        '@@SECTION_BODY@@\n' r'\bibliographystyle{plain}\bibliography{references/demo}' '\n'
        r'\clearpage\section*{Synthetic sensor field / 合成传感器场}' '\n'
        r'This fixture is generated by xorshift32 with seed 123456789. It contains synthetic data only.\par' '\n'
        r'\includegraphics[width=.9\linewidth]{materials/synthetic-field.png}' '\n' r'\end{document}' '\n')
    templates = {}
    for lang in ['en', 'zh']:
        language_template = template
        if lang == 'en':
            language_template = template.replace(r'\begin{document}', r'\renewcommand{\refname}{References}' + '\n' + r'\begin{document}')
        path = paper / 'templates' / (lang + '.tex'); path.write_text(language_template)
        templates[lang] = {'path': 'templates/' + path.name, 'sha256': file_sha(path)}
    cfg = {'schema_version': 1, 'software_id': 'webcodex-paper-studio', 'extension_version': '0.8.0-dev',
        'admission_profile': 'paper-editor.v2', 'instance_id': 'workflow-synthetic', 'client_id': 'workflow-synthetic',
        'project_id': 'bilingual-synthetic', 'project_root': str(paper), 'artifact_root': str(paper / 'builds'),
        'artifact_layout': 'project-builds-v1', 'state_root': str(output / 'state'),
        'writable_roots': ['chapters', 'reviews'], 'readonly_roots': ['templates', 'materials', 'references', 'builds'],
        'native_project': 'agent:workflow-synthetic:project', 'native_artifact_project': 'agent:workflow-synthetic:artifacts',
        'chapter_workflow': {'root': 'chapters', 'templates': templates}, 'drive_folder_id': None,
        'toolchain': {'python_prefix': sys.prefix, 'texlive_root': str(no_links(Path(texlive_root)))},
        'limits': {'timeout_seconds': 180, 'max_output_bytes': 64 * 1024**2, 'max_snapshot_bytes': 16 * 1024**2, 'max_files': 2048},
        'execution_policy': {'tex_targets': {}, 'figure_root': 'figures', 'figure_map': 'figures/map.json',
            'expected_figures': 0, 'expected_tables': 0, 'render_tex_previews': True}}
    config_path = output / 'instance.json'; atomic_json(config_path, cfg)
    cfg = load_config(config_path)
    report = {'schema': 'paper-studio.bilingual-example.v1', 'project_id': cfg['project_id'], 'output_root': str(output),
        'config_path': str(config_path), 'synthetic': True, 'revisions': {},
        'chatgpt_web_acceptance': 'not_performed', 'local_receiver_verified': False}
    previous_material = 'absent'; previous_section = 'absent'
    for revision, accuracy in [('r01', 0.81), ('r02', 0.84)]:
        result_path = project / 'results' / (revision + '.json')
        atomic_json(result_path, {'synthetic': True, 'accuracy': accuracy, 'samples': 100, 'split': 'synthetic-held-out'})
        spec = {'schema': 'paper-studio.material-handoff-input.v1', 'project_id': cfg['project_id'],
            'change_id': revision, 'title': 'Synthetic evaluation ' + revision,
            'summary': 'Synthetic accuracy updated to ' + str(accuracy),
            'sources': [{'path': 'results/' + result_path.name, 'sha256': file_sha(result_path), 'role': 'experiment_summary'}],
            'evidence': [{'id': 'E_accuracy', 'kind': 'measured_fact', 'statement': 'Synthetic fixture accuracy ' + str(accuracy),
                'sources': [{'path': 'results/' + result_path.name, 'locator': {'json_pointer': '/accuracy'}}]}],
            'impacts': {'claims': [{'id': 'C_accuracy', 'path': 'chapters/methods/' + revision + '/main_en.tex', 'reason': 'Synthetic metric changed'}],
                'figures': [], 'sections': [{'id': 'methods', 'path': 'chapters/methods/' + revision + '/main_en.tex', 'reason': 'Update reported accuracy'}]}}
        handoff = create_handoff(project_root=project, paper_root=paper, project_id=cfg['project_id'],
            spec=spec, expected_previous=previous_material)
        previous_material = handoff['material_revision']
        bodies = {'en': (r'\section{Method and synthetic evaluation}' '\n'
            'We demonstrate the writing workflow using 100 synthetic held-out observations. '
            f'The recorded accuracy is {accuracy:.2f}. These values exercise revision tracking and carry no empirical research claim. '
            r'The fixture description is indexed as~\cite{SyntheticFixture2026}.' '\n'),
            'zh': (r'\section{方法与合成评估}' '\n'
            f'本例使用100个合成留出观测演示写作流程，记录准确率为{accuracy:.2f}。这些数值用于检验修订追踪，不构成实测科研结论。'
            r'示例说明登记为~\cite{SyntheticFixture2026}。' '\n')}
        material_manifest = str(Path(handoff['manifest_path']).relative_to(paper))
        stage = dispatch(cfg, {'action': 'stage', 'section_id': 'methods', 'revision': revision,
            'scope': 'Method and synthetic evaluation / 方法与合成评估', 'expected_previous_sha256': previous_section,
            'bodies': bodies, 'material_manifest': material_manifest, 'material_revision': previous_material, 'dry_run': False})
        previous_section = stage['manifest_sha256']
        pairs = {}
        for language, tex_path in stage['tex_paths'].items():
            plan = build_plan(cfg, tex_path)
            build = jobs.submit(cfg, 'tex', {'request_id': 'example_' + revision + '_' + language,
                'tex_path': tex_path, 'expected_revision': plan['expected_revision'], 'expected_input_sha256': plan['input_sha256'],
                'build_profile': 'xelatex', 'use_latexmk': False})
            deadline = time.monotonic() + 210
            while build['status'] in {'queued', 'running'} and time.monotonic() < deadline:
                time.sleep(1)
                build = jobs.read_status(cfg, build['build_id'], tail_lines=10)
            if build['status'] != 'completed':raise RuntimeError(json.dumps(build, ensure_ascii=False))
            pdf = next(item for item in build['artifacts'] if item['path'].endswith('.pdf'))
            def call(name, arguments):
                arguments = dict(arguments); arguments.pop('project_id')
                return jobs.artifact(cfg, **arguments)
            received = receive(call, project_id=cfg['project_id'], build_id=build['build_id'], path=pdf['path'],
                destination=output / 'downloads' / (revision + '_' + language + '.pdf'), expected_sha256=pdf['sha256'])
            if received['chunks'] < 2:raise RuntimeError('Example must exercise multi-chunk transfer')
            pairs[language] = {'build_id': build['build_id'], 'path': pdf['path'], 'bytes': pdf['bytes'],
                'sha256': pdf['sha256'], 'pages': build['result']['pages'], 'receipt': received}
        archive = save_version(cfg, 'methods-' + revision, [row['build_id'] for row in pairs.values()],
            'Synthetic bilingual section ' + revision)
        report['revisions'][revision] = {'material': handoff, 'section': stage, 'languages': pairs, 'archive': archive}
        atomic_json(output / 'report.json', report)
    compared = dispatch(cfg, {'action': 'compare', 'section_id': 'methods', 'left_revision': 'r01', 'right_revision': 'r02'})
    (output / 'revision-comparison.html').write_text(compared.pop('html'))
    atomic_json(output / 'revision-comparison.json', compared)
    report.update(local_receiver_verified=True, comparison_path=str(output / 'revision-comparison.html'))
    atomic_json(output / 'report.json', report)
    print(json.dumps({'report': str(output / 'report.json'), 'revisions': report['revisions']}, ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output-root', required=True)
    parser.add_argument('--texlive-root', required=True)
    options = parser.parse_args()
    run(options.output_root, options.texlive_root)
