"""Generate Paper Editor consumers from the reconciled repo distribution source.

The WSL canonical skill is reconciled into this source before packaging.
No account publishing, service changes or secret access. App/Windows consumers
are hash-checked generated copies, never an alternative authoring source.
"""
from __future__ import annotations
import argparse,hashlib,json,os,re,shutil,sysconfig,tempfile,zipfile
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'skills/paper-editor'
if not (SOURCE/'SKILL.md').is_file():
    SOURCE=Path(sysconfig.get_path('data'))/'share/webPaperWriting/skills/paper-editor'
VERSION='0.9.11'
CONTRACT='paper-editor.project.v1'

def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def source_manifest():
    files={}
    for path in sorted(SOURCE.rglob('*')):
        if path.is_symlink():raise ValueError('Skill source must not contain symlinks')
        if path.is_file():files[path.relative_to(SOURCE).as_posix()]=digest(path)
    if 'SKILL.md' not in files:raise ValueError('Skill source missing')
    for path in SOURCE.rglob('*.md'):
        for link in re.findall(r'\]\(([^)]+)\)',path.read_text(encoding='utf-8')):
            if '://' in link or link.startswith('#'):continue
            target=(path.parent/link.split('#')[0]).resolve()
            if not target.is_relative_to(SOURCE) or not target.is_file():raise ValueError('Broken or escaping reference '+link)
    return {'version':VERSION,'skill_contract_version':CONTRACT,'source':str(SOURCE),'files':files}

def style_component(original=None):
    """Derive the discoverable style skill from the bundled rulebook.

    Existing sibling components belong to the selected plugin. Leave their
    files intact and report them so a caller can review any independent edits.
    New consumers receive the same rule bytes as paper-editor itself.
    """
    rulebook=SOURCE/'references/anti-defensive-writing.md'
    license_file=SOURCE/'references/anti-defensive-writing-LICENSE.md'
    if not rulebook.is_file() or not license_file.is_file():
        raise ValueError('Style component requires the bundled rulebook and its license')
    rule_bytes=rulebook.read_bytes()
    if not rule_bytes.startswith(b'---\nname: anti-defensive-writing\n'):
        raise ValueError('Bundled style rulebook has an unexpected skill identity')
    prefix='skills/anti-defensive-writing/'
    agent='''interface:
  display_name: "反防御写作"
  short_description: "中英文学术写作：删冗余防御，保留事实与方法条件"
  default_prompt: "使用 $anti-defensive-writing 审查和润色当前文字，按原文检查流程删除冗余防御措辞，保留科研证据、数值、引用、真实局限及作者原意。"
policy:
  allow_implicit_invocation: true
'''
    attribution='''# Upstream attribution and license

The rulebook in this component is generated byte-for-byte from
[the shared paper-editor rulebook](../../paper-editor/references/anti-defensive-writing.md).
Source and license are maintained together in the paper-editor source tree.
Upstream source is Kiterlin/anti-defensive-writing at commit
f516147d017a3fe43ae99192cb89d8261b0c8679.

'''+license_file.read_text(encoding='utf-8')
    generated={prefix+'SKILL.md':rule_bytes,
               prefix+'agents/openai.yaml':agent.encode(),
               prefix+'references/UPSTREAM-LICENSE.md':attribution.encode()}
    existing=set((original or {}).get('contents',{}))
    existing.update(row['path'] for row in (original or {}).get('files',[]))
    preserved=sorted(path for path in existing if path.startswith(prefix))
    if preserved and prefix+'SKILL.md' not in existing:
        raise ValueError('Existing style component has no SKILL.md; inspect it before replacement')
    # Preserve a whole independently installed sibling skill. Filling only its
    # missing files could accidentally impose our policy on a custom component.
    selected={} if preserved else generated
    receipt={'rulebook_source':'references/anti-defensive-writing.md',
             'rulebook_sha256':hashlib.sha256(rule_bytes).hexdigest(),
             'mode':'preserved_existing' if preserved else 'generated_from_shared_rulebook',
             'added_files':{path:hashlib.sha256(raw).hexdigest() for path,raw in selected.items()},
             'preserved_paths':preserved}
    return selected,receipt


def install(target, *, backup_root=None):
    manifest=source_manifest();target=Path(target).absolute()
    if target.is_symlink():raise ValueError('Refusing existing symlink install target')
    if target.exists():
        marker=target/'.paper-editor-generated.json'
        if not marker.is_file():raise ValueError('Unmanaged existing install: '+str(target))
        old=json.loads(marker.read_text(encoding='utf-8'))
        current={p.relative_to(target).as_posix():digest(p) for p in target.rglob('*') if p.is_file() and p!=marker}
        if current!=old['files']:raise ValueError('User-edited installed copy; refusing overwrite')
        if current==manifest['files']:return {'target':str(target),'status':'unchanged'}
        # Versions are never replaced in place without a saved generated copy. A label
        # installed twice (a reviewed draft, then its final) is archived by content.
        history_root=Path(backup_root) if backup_root else Path(os.environ.get('XDG_STATE_HOME',Path.home()/'.local/state'))/'webcodex-paper-studio/skill-backups'
        base=history_root/hashlib.sha256(str(target).encode()).hexdigest()[:12]
        content=hashlib.sha256(json.dumps(current,sort_keys=True).encode()).hexdigest()[:12]
        base.mkdir(parents=True,exist_ok=True)
        for history in (base/old['version'],base/(old['version']+'-'+content)):
            if not history.exists():
                shutil.copytree(target,history);break
            saved={p.relative_to(history).as_posix():digest(p) for p in history.rglob('*') if p.is_file() and p.name!='.paper-editor-generated.json'}
            if saved==current:break
        else:raise ValueError('Prior install archives differ from the installed copy')
    target.parent.mkdir(parents=True,exist_ok=True)
    stage=Path(tempfile.mkdtemp(prefix='.paper-editor-',dir=target.parent))
    try:
        shutil.copytree(SOURCE,stage,dirs_exist_ok=True)
        (stage/'.paper-editor-generated.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n', encoding='utf-8', newline='\n')
        if target.exists():
            old_path=stage.with_name(stage.name+'-old');os.replace(target,old_path)
            try:os.replace(stage,target)
            except BaseException:os.replace(old_path,target);raise
            shutil.rmtree(old_path)
        else:os.replace(stage,target)
    finally:
        if stage.exists():shutil.rmtree(stage)
    for rel,expected in manifest['files'].items():
        if digest(target/rel)!=expected:raise ValueError('Install readback mismatch')
    return {'target':str(target),'status':'installed','files':len(manifest['files'])}

def require_version_increase(current, proposed):
    def components(value):
        if not isinstance(value, str) or not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', value):
            raise ValueError('Plugin package versions must be strict stable semantic versions')
        return tuple(map(int, value.split('.')))
    if components(proposed) <= components(current):
        raise ValueError('Plugin package version must increase independently of the Skill version')


def package(output,expected_release_id=None,*,migration_snapshot=None,preserve_presentation=False,plugin_version=None):
    if expected_release_id is not None and not re.fullmatch(r'pluginrel_[0-9a-f]{32}',expected_release_id):
        raise ValueError('expected_release_id must be the live plugin release read immediately before publishing')
    original = json.loads(Path(migration_snapshot).read_text(encoding='utf-8')) if migration_snapshot else None
    current_snapshot = bool(original and expected_release_id and original['plugin']['current_release_id'] == expected_release_id)
    if plugin_version is not None and not current_snapshot:
        raise ValueError('An independent plugin version requires the current release and its matching snapshot')
    release_version = plugin_version if plugin_version is not None else VERSION
    if current_snapshot:
        require_version_increase(original['plugin']['version'], release_version)
    manifest=source_manifest();style_files,style_receipt=style_component(original)
    out=Path(output).absolute();out.mkdir(parents=True,exist_ok=True)
    if original:
        plugin = json.loads(original['contents']['plugin.json'])
        overlay = json.loads(original['contents']['.codex-plugin/plugin.json'])
    else:
        interface = {'category': 'Scientific Research', 'capabilities': [],
                     'developerName': 'webPaperWriting contributors',
                     'defaultPrompt': ['启用 web论文写作，在我选择的项目中写作，每次起草或返修时使用随包的反防御写作规则。']}
        plugin = {'$schema':'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json',
                  'name':'paper-editor','author':{'name':'webPaperWriting contributors'},
                  'extensions':{'com.openai':{'interface':interface}}}
        overlay = {'name':'paper-editor','author':plugin['author'],'skills':'./skills/'}
    description = 'web论文写作（Chat论文写作）：webPaperWriting 的共享技能。Codex 交接实验材料，Chat 沿用所选项目连接，使用随包的反防御写作规则完成双语撰写和返修。'
    plugin.update(version=release_version)
    interface = plugin['extensions']['com.openai']['interface']
    overlay.update(version=release_version)
    if not original or not preserve_presentation:
        plugin['description']=description
        prompts = interface.get('defaultPrompt')
        if original and isinstance(prompts, list):
            interface['defaultPrompt'] = [
                prompt.replace('SCI 科研论文工作流', 'web论文写作').replace('论文编辑器', 'web论文写作').replace('Chat论文写作', 'web论文写作')
                for prompt in prompts
            ]
        interface.update(displayName='web论文写作',shortDescription='科研材料与双语论文写作',longDescription=description)
        overlay.update(description=description,interface=interface)
    alias='''---
name: sci-paper-workflow
description: 仅在用户明确调用旧名称 SCI 科研论文工作流时使用的兼容入口；日常 web论文写作任务使用 paper-editor。
---

# 兼容入口

本入口不维护独立流程。立即读取 [web论文写作](../paper-editor/SKILL.md)，按实际宿主分工并沿用其项目契约与参考。旧名称不授予额外权限，不重复加载旧工作流。
'''
    alias_agent='''interface:
  display_name: "web论文写作（旧入口兼容）"
  short_description: "仅手动兼容旧称；统一执行 web论文写作的宿主路由与项目契约"
  default_prompt: "使用 $paper-editor web论文写作接续原 SCI 科研论文工作流。"
policy:
  allow_implicit_invocation: false
  products: [CHAT]
'''
    archive=out/f'paper-editor-{release_version}.zip'
    def put(z, name, contents):
        info = zipfile.ZipInfo(name, date_time=(1980,1,1,0,0,0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        z.writestr(info, contents)
    with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
        put(z,'plugin.json',json.dumps(plugin,ensure_ascii=False,indent=2)+'\n')
        put(z,'.codex-plugin/plugin.json',json.dumps(overlay,ensure_ascii=False,indent=2)+'\n')
        put(z,'agents/openai.yaml',(SOURCE/'agents/openai.yaml').read_text(encoding='utf-8')+'  products: [CHAT]\n')
        for rel in manifest['files']:put(z,'skills/paper-editor/'+rel,(SOURCE/rel).read_bytes())
        put(z,'skills/sci-paper-workflow/SKILL.md',alias)
        put(z,'skills/sci-paper-workflow/agents/openai.yaml',alias_agent)
        for relative,raw in style_files.items():put(z,relative,raw)
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None
        assert json.loads(z.read('plugin.json'))['extensions']['com.openai']['interface']['defaultPrompt']==interface['defaultPrompt']
    receipt={'archive':str(archive),'sha256':digest(archive),'version':release_version,'skill_version':VERSION,'skill_contract_version':CONTRACT,
             'plugin_id':original['plugin']['plugin_id'] if original else None,
             # Conditional cloud updates must use the live release read just before publishing;
             # the original snapshot release is kept only as provenance.
             'expected_release_id':expected_release_id,'original_snapshot_release_id':original['plugin']['current_release_id'] if original else None,
             'delete_paths':[f['path'] for f in (original['files'] if original else []) if f['path'].startswith('skills/sci-paper-workflow/references/')],
             'source_manifest':manifest,'style_component':style_receipt,
             'account_status':'not_updated_by_packaging'}
    (out/'package-receipt.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2)+'\n', encoding='utf-8', newline='\n')
    return receipt


def app_skill_package(output, *, snapshot, expected_release_id, plugin_version):
    """Overlay the shared writing skills while preserving an existing App package.

    Skill and App semantic versions are independent. The ordinary standalone
    package intentionally owns presentation; this mode leaves every existing
    App manifest field unchanged except version and retains all omitted files.
    """
    original=json.loads(Path(snapshot).read_text(encoding='utf-8'))
    metadata=original['plugin'];contents=original['contents']
    if (not re.fullmatch(r'(?:pluginrel_|PluginRelease_)[0-9a-f]{32}',expected_release_id or '')
        or metadata.get('current_release_id')!=expected_release_id):
        raise ValueError('App skill overlay requires the current observed release')
    require_version_increase(metadata['version'], plugin_version)
    required={'.codex-plugin/plugin.json','.app.json'}
    if not required<=set(contents) or not required<={row['path'] for row in original['files']}:
        raise ValueError('App skill overlay requires its exact existing App manifests')
    names=['plugin.json','.codex-plugin/plugin.json'] if 'plugin.json' in contents else ['.codex-plugin/plugin.json']
    manifests={name:json.loads(contents[name]) for name in names}
    for value in manifests.values():
        if value.get('version')!=metadata['version'] or value.get('name')!=metadata['name']:
            raise ValueError('App manifest identity/version differs from the source snapshot')
    app=json.loads(contents['.app.json'])
    if not app.get('apps') or not manifests['.codex-plugin/plugin.json'].get('apps'):
        raise ValueError('App skill overlay must retain an actual App binding')
    if 'plugin.json' not in manifests:
        legacy=manifests['.codex-plugin/plugin.json']
        if legacy.get('skills') not in (None,'./skills','./skills/'):
            raise ValueError('Legacy App skill overlay requires the standard skills directory')
        manifests['.codex-plugin/plugin.json']={**legacy,'skills':'./skills'}
    manifest=source_manifest();style_files,style_receipt=style_component(original)
    out=Path(output).absolute();out.mkdir(parents=True,exist_ok=True)
    archive=out/f'paper-editor-{VERSION}-app-{plugin_version}-skills.zip'
    with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as zipped:
        def put(name,raw):
            info=zipfile.ZipInfo(name,date_time=(1980,1,1,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o100644<<16
            zipped.writestr(info,raw)
        for name,value in manifests.items():
            updated={**value,'version':plugin_version}
            put(name,json.dumps(updated,ensure_ascii=False,indent=2)+'\n')
        for relative in manifest['files']:
            put('skills/paper-editor/'+relative,(SOURCE/relative).read_bytes())
        for relative,raw in style_files.items():put(relative,raw)
    with zipfile.ZipFile(archive) as zipped:
        if zipped.testzip() is not None:raise ValueError('App skill overlay ZIP failed verification')
        for name,value in manifests.items():
            updated=json.loads(zipped.read(name));updated['version']=value['version']
            if updated!=value:raise ValueError('App configuration changed during skill packaging')
        for relative,expected in manifest['files'].items():
            if hashlib.sha256(zipped.read('skills/paper-editor/'+relative)).hexdigest()!=expected:
                raise ValueError('App skill overlay source hash mismatch')
    receipt={'archive':str(archive),'sha256':digest(archive),'version':plugin_version,'skill_version':VERSION,
             'plugin_id':metadata['plugin_id'],'expected_release_id':expected_release_id,
             'source_manifest':manifest,'style_component':style_receipt,
             'skill_contract_version':CONTRACT,'delete_paths':[],
             'mode':'existing_app_skills_only','app_binding_preserved':True,
             'account_status':'not_updated_by_packaging'}
    (out/'app-skill-package-receipt.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2)+'\n', encoding='utf-8', newline='\n')
    return receipt

def main():
    p=argparse.ArgumentParser();p.add_argument('--output',required=True);p.add_argument('--install',action='append',default=[])
    p.add_argument('--expected-release-id',help='Live plugin release ID read immediately before an approved cloud update')
    p.add_argument('--migration-snapshot', help='Optional private manifest of the existing plugin for an in-place upgrade')
    p.add_argument('--preserve-presentation',action='store_true',help='Retain existing standalone plugin descriptions and full interface during a skill-only update')
    p.add_argument('--app-skills-snapshot',help='Current App snapshot; overlay shared skills and version, preserving existing components')
    p.add_argument('--plugin-version',help='Strictly greater distribution version for the current App or standalone plugin snapshot')
    args=p.parse_args()
    if args.app_skills_snapshot:
        if args.migration_snapshot or not args.expected_release_id or not args.plugin_version:
            p.error('App skill mode requires --expected-release-id/--plugin-version and no migration snapshot')
        result=app_skill_package(args.output,snapshot=args.app_skills_snapshot,
            expected_release_id=args.expected_release_id,plugin_version=args.plugin_version)
    else:
        result=package(args.output,args.expected_release_id,migration_snapshot=args.migration_snapshot,
            preserve_presentation=args.preserve_presentation,plugin_version=args.plugin_version)
    result['installs']=[install(path) for path in args.install]
    print(json.dumps({k:v for k,v in result.items() if k!='source_manifest'},ensure_ascii=False,indent=2))
if __name__=='__main__':main()

